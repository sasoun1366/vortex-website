const LANGS = ["fa", "en"];
const RTL = ["fa"];

function t(key, lang) {
  lang = lang || window.VORTEX_LANG || "fa";
  const bag = I18N[lang] || I18N.fa;
  return (key in bag) ? bag[key] : (I18N.fa[key] !== undefined ? I18N.fa[key] : key);
}

/* Persian digits + thousand separators (or standard for EN) */
function money(num, lang) {
  lang = lang || window.VORTEX_LANG || "fa";
  const n = Math.round(Number(num) || 0);
  const s = new Intl.NumberFormat(lang === "fa" ? "fa-IR" : "en-US").format(n);
  return s + " " + (VORTEX.config.currency[lang] || "");
}

/* plain number, localized digits */
function num(n, lang) {
  lang = lang || window.VORTEX_LANG || "fa";
  return new Intl.NumberFormat(lang === "fa" ? "fa-IR" : "en-US").format(Number(n) || 0);
}

/* pick the right language field of a bilingual object */
function pick(obj, lang) {
  lang = lang || window.VORTEX_LANG || "fa";
  if (!obj) return "";
  if (typeof obj === "string") return obj;
  return obj[lang] || obj.fa || obj.en || "";
}
